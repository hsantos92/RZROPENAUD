def make_mic_volume_report(volume: int) -> bytes:
    """Create command to set microphone volume (0-100%)."""
    clamped = max(0, min(100, volume))
    # Arguments: [volume]
    return build_razer_report(
        command_class=COMMAND_CLASS_AUDIO,
        command_id=CMD_ID_SET_MIC_VOLUME,
        args=[clamped],
    )


def make_get_mic_volume_report() -> bytes:
    """Create command to query current microphone volume."""
    return build_razer_report(
        command_class=COMMAND_CLASS_AUDIO,
        command_id=CMD_ID_GET_MIC_VOLUME,
        args=[0x00],
    )


def make_sidetone_report(volume: int, enabled: Optional[bool] = None) -> bytes:
    """Create command to set sidetone (mic monitoring) level (0-100%) and enable toggle."""
    clamped = max(0, min(100, volume))
    is_on = (clamped > 0) if enabled is None else enabled
    # Arguments: [enabled (0x01/0x00), volume (0-100)]
    return build_razer_report(
        command_class=COMMAND_CLASS_AUDIO,
        command_id=CMD_ID_SET_SIDETONE,
        args=[0x01 if is_on else 0x00, clamped],
    )


def make_get_sidetone_report() -> bytes:
    """Create command to query current sidetone level."""
    return build_razer_report(
        command_class=COMMAND_CLASS_AUDIO,
        command_id=CMD_ID_GET_SIDETONE,
        args=[0x00],
    )


def make_equalizer_report(preset_idx: int, bands: List[int]) -> bytes:
    """Create command to set 10-band equalizer settings.

    bands: list of 10 integer gain values (typically -12 to +12 dB).
    """
    clamped_bands = [max(-12, min(12, int(b))) for b in bands[:10]]
    while len(clamped_bands) < 10:
        clamped_bands.append(0)

    # Encode gains: signed 8-bit integers (& 0xFF)
    encoded = [b & 0xFF for b in clamped_bands]
    # Arguments: [preset_id, band0, band1, ..., band9]
    return build_razer_report(
        command_class=COMMAND_CLASS_AUDIO,
        command_id=CMD_ID_SET_EQUALIZER,
        args=[preset_idx & 0xFF] + encoded,
    )


