def write_surround_config(
    target_file: Optional[Path] = None,
    sofa_path: Optional[str] = None,
) -> Path:
    """Write the PipeWire filter-chain configuration to disk.

    Args:
        target_file: Destination file path (defaults to SURROUND_CONF_FILE).
        sofa_path: Path to SOFA HRTF model (defaults to get_sofa_path()).

    Returns:
        Path to the written configuration file.
    """
    dest = target_file or SURROUND_CONF_FILE
    dest.parent.mkdir(parents=True, exist_ok=True)

    actual_sofa = sofa_path or (str(get_sofa_path()) if get_sofa_path() else "/usr/share/libmysofa/default.sofa")
    content = generate_surround_config(actual_sofa)

    tmp_file = dest.parent / f"{dest.name}.tmp.{os.getpid()}"
    with open(tmp_file, "w", encoding="utf-8") as f:
        f.write(content)
    tmp_file.replace(dest)
    logger.debug("Wrote surround configuration to %s", dest)
    return dest


def ensure_systemd_service() -> Path:
    """Create systemd user service unit for 7.1 Virtual Surround if missing or outdated.

    Returns:
        Path to the service file.
    """
    service_content = f"""[Unit]
Description=Razer BlackShark V2 7.1 Virtual Surround Sound (PipeWire)
After=pipewire.service
PartOf=pipewire.service

[Service]
Type=simple
ExecStart=/usr/bin/pipewire -c {SURROUND_CONF_FILE}
Restart=on-failure
RestartSec=2

[Install]
WantedBy=default.target
"""
    SURROUND_SERVICE_FILE.parent.mkdir(parents=True, exist_ok=True)
    if not SURROUND_SERVICE_FILE.exists() or SURROUND_SERVICE_FILE.read_text(encoding="utf-8") != service_content:
        SURROUND_SERVICE_FILE.write_text(service_content, encoding="utf-8")
        try:
            subprocess.run(["systemctl", "--user", "daemon-reload"], capture_output=True, check=False)
        except Exception:
            pass
    return SURROUND_SERVICE_FILE


def is_systemd_user_available() -> bool:
    """Check if systemctl --user is available and active."""
    if not shutil.which("systemctl"):
        return False
    try:
        proc = subprocess.run(
            ["systemctl", "--user", "is-system-running"],
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
        return proc.returncode == 0 or proc.stdout.strip() in ("running", "degraded")
    except Exception:
        return False


def is_surround_active() -> bool:
    """Check if 7.1 Virtual Surround sink is currently registered and active in PipeWire.

    Returns:
        True if the 8-channel virtual sink node exists, False otherwise.
    """
    # 1. Fast check via pw-cli
    if shutil.which("pw-cli"):
        try:
            proc = subprocess.run(
                ["pw-cli", "info", SURROUND_SINK_NAME],
                capture_output=True,
                text=True,
                timeout=2,
                check=False,
            )
            if proc.returncode == 0 and SURROUND_SINK_NAME in proc.stdout:
                return True
        except Exception:
            pass

    # 2. Check via pactl sinks
    if shutil.which("pactl"):
        try:
            proc = subprocess.run(
                ["pactl", "list", "sinks", "short"],
                capture_output=True,
                text=True,
                timeout=2,
                check=False,
            )
            if proc.returncode == 0 and SURROUND_SINK_NAME in proc.stdout:
                return True
        except Exception:
            pass

    # 3. Check systemd unit status
    if is_systemd_user_available():
        try:
            proc = subprocess.run(
                ["systemctl", "--user", "is-active", SURROUND_SERVICE_NAME],
                capture_output=True,
                text=True,
                timeout=2,
                check=False,
            )
            if proc.returncode == 0 and proc.stdout.strip() == "active":
                return True
        except Exception:
            pass

    return False


def enable_surround(sofa_path: Optional[str] = None) -> bool:
    """Enable and activate 7.1 Virtual Surround Sound.

    Writes the filter-chain configuration, launches the service/daemon,
    and un-mutes / sets all 8 channels to 100% volume.

    Args:
        sofa_path: Optional custom path to SOFA HRTF model.

    Returns:
        True if successfully enabled and active, False otherwise.
    """
    supported, msg = is_surround_supported()
    if not supported:
        logger.error("Cannot enable 7.1 surround: %s", msg)
        return False

    # 1. Write configuration
    write_surround_config(sofa_path=sofa_path)

    # 2. Start service via systemd if available
    started = False
    if is_systemd_user_available():
        ensure_systemd_service()
        try:
            subprocess.run(
                ["systemctl", "--user", "start", SURROUND_SERVICE_NAME],
                capture_output=True,
                check=False,
                timeout=5,
            )
            subprocess.run(
                ["systemctl", "--user", "enable", SURROUND_SERVICE_NAME],
                capture_output=True,
                check=False,
                timeout=5,
            )
            started = True
        except Exception as e:
            logger.warning("Failed to start surround via systemd: %s", e)

    # 3. Fallback to background process if systemd not active or failed
    if not started:
        # Check if already running standalone
        if SURROUND_PID_FILE.exists():
            try:
                pid = int(SURROUND_PID_FILE.read_text(encoding="utf-8").strip())
                os.kill(pid, 0)
                started = True
            except Exception:
                SURROUND_PID_FILE.unlink(missing_ok=True)

        if not started:
            try:
                pipewire_bin = shutil.which("pipewire") or "/usr/bin/pipewire"
                proc = subprocess.Popen(
                    [pipewire_bin, "-c", str(SURROUND_CONF_FILE)],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                    start_new_session=True,
                )
                SURROUND_PID_FILE.write_text(str(proc.pid), encoding="utf-8")
                started = True
            except Exception as e:
                logger.error("Failed to start standalone pipewire filter-chain: %s", e)
                return False

    # 4. Wait up to 3 seconds for node to register in PipeWire
    for _ in range(15):
        time.sleep(0.2)
        if is_surround_active():
            break

    # 5. Normalize volumes: set all 8 channels to 100% (0 dB)
    if shutil.which("pactl"):
        try:
            subprocess.run(
                ["pactl", "set-sink-volume", SURROUND_SINK_NAME, "100%"],
                capture_output=True,
                check=False,
                timeout=2,
            )
        except Exception:
            pass

    set_surround_7_1_enabled(True)
    return is_surround_active()


def disable_surround() -> bool:
    """Disable and stop 7.1 Virtual Surround Sound.

    Stops and disables systemd unit, or terminates background process.

    Returns:
        True if successfully stopped, False otherwise.
    """
    # 1. Stop systemd unit
    if is_systemd_user_available():
        try:
            subprocess.run(
                ["systemctl", "--user", "stop", SURROUND_SERVICE_NAME],
                capture_output=True,
                check=False,
                timeout=5,
            )
            subprocess.run(
                ["systemctl", "--user", "disable", SURROUND_SERVICE_NAME],
                capture_output=True,
                check=False,
                timeout=5,
            )
        except Exception as e:
            logger.warning("Failed to stop surround systemd service: %s", e)

    # 2. Terminate background process if any
    if SURROUND_PID_FILE.exists():
        try:
            pid = int(SURROUND_PID_FILE.read_text(encoding="utf-8").strip())
            os.kill(pid, 15)  # SIGTERM
            time.sleep(0.3)
            try:
                os.kill(pid, 0)
                os.kill(pid, 9)  # SIGKILL if still running
            except OSError:
                pass
        except Exception as e:
            logger.debug("Failed terminating PID %s: %s", SURROUND_PID_FILE, e)
        finally:
            SURROUND_PID_FILE.unlink(missing_ok=True)

    set_surround_7_1_enabled(False)

    # Wait briefly for node cleanup
    for _ in range(5):
        time.sleep(0.1)
        if not is_surround_active():
            break

    return not is_surround_active()


def get_surround_status() -> Dict[str, Any]:
    """Retrieve full status information for 7.1 Virtual Surround.

    Returns:
        Dictionary containing status details.
    """
    supported, msg = is_surround_supported()
    sofa = get_sofa_path()
    active = is_surround_active()
    return {
        "supported": supported,
        "message": msg,
        "active": active,
        "config_enabled": get_surround_7_1_enabled(),
        "sofa_path": str(sofa) if sofa else None,
        "sink_name": SURROUND_SINK_NAME,
        "output_name": SURROUND_OUTPUT_NAME,
        "channels": 8,
        "channel_map": "FL FR FC LFE RL RR SL SR",
    }
