"""PipeWire 7.1 Virtual Surround Sound integration for Razer BlackShark V2.

Downmixes 8-channel audio (FL, FR, FC, LFE, RL, RR, SL, SR) into binaural stereo
for the Razer BlackShark V2 headphone drivers using HRTF (SOFA spatializer).
"""

from __future__ import annotations

import logging
import os
import shutil
import subprocess
import time
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

from rzropenaud_io.config import (
    CONFIG_DIR,
    get_surround_7_1_enabled,
    set_surround_7_1_enabled,
)

logger = logging.getLogger(__name__)

SURROUND_SINK_NAME = "effect_input.razer_virtual_surround_7_1"
SURROUND_OUTPUT_NAME = "effect_output.razer_virtual_surround_7_1"
SURROUND_CONF_FILE = CONFIG_DIR / "razer-7.1-surround.conf"
SURROUND_SERVICE_NAME = "rzr-surround-7-1.service"
SURROUND_SERVICE_FILE = Path.home() / ".config" / "systemd" / "user" / SURROUND_SERVICE_NAME
SURROUND_PID_FILE = CONFIG_DIR / "surround.pid"

CANDIDATE_SOFA_PATHS = [
    Path("/usr/share/libmysofa/default.sofa"),
    Path("/usr/share/libmysofa/MIT_KEMAR_normal_pinna.sofa"),
    Path("/usr/local/share/libmysofa/default.sofa"),
    Path("/usr/share/pipewire/filter-chain/default.sofa"),
]


def get_sofa_path() -> Optional[Path]:
    """Find the best available SOFA HRTF model file on the system.

    Returns:
        Path to SOFA file if found, None otherwise.
    """
    for p in CANDIDATE_SOFA_PATHS:
        if p.exists() and p.is_file():
            return p
    return None


def is_surround_supported() -> Tuple[bool, str]:
    """Check if the system supports PipeWire filter-chain HRTF surround sound.

    Returns:
        Tuple of (is_supported: bool, message: str).
    """
    if not shutil.which("pipewire"):
        return False, "PipeWire executable not found in PATH."

    sofa_path = get_sofa_path()
    if sofa_path is None:
        return False, "No SOFA HRTF profile found (install libmysofa or provide ~/.config/rzropenaud/hrtf.sofa)."

    # Check for PipeWire filter chain module or spa plugin
    fc_module = Path("/usr/lib/pipewire-0.3/libpipewire-module-filter-chain.so")
    spa_sofa = Path("/usr/lib/spa-0.2/filter-graph/libspa-filter-graph-plugin-sofa.so")

    if not (fc_module.exists() or spa_sofa.exists()):
        # Try finding via ldconfig or test run
        logger.warning("Standard module paths not found directly, will attempt runtime test.")

    return True, "Supported"


